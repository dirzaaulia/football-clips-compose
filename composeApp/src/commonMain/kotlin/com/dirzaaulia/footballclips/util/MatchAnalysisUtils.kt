package com.dirzaaulia.footballclips.util

import com.dirzaaulia.footballclips.domain.model.Match

object MatchAnalysisUtils {

    fun isUpcoming(match: Match): Boolean {
        val s = match.status.uppercase()
        return s != "FINISHED" && s != "IN_PLAY" && s != "PAUSED" && s != "LIVE"
    }

    fun isLive(match: Match): Boolean {
        val s = match.status.uppercase()
        return s == "IN_PLAY" || s == "PAUSED" || s == "LIVE"
    }

    fun isFinished(match: Match): Boolean {
        return match.status.uppercase() == "FINISHED"
    }

    fun getSummaryOrPreview(match: Match): String {
        val home = match.homeTeamName.ifBlank { "Home Team" }
        val away = match.awayTeamName.ifBlank { "Away Team" }
        val comp = match.competitionName.ifBlank { "Official League" }

        // 1. Upcoming Fixtures: Return editorial preview or algorithmic preview without AI
        if (isUpcoming(match)) {
            if (!match.editorialStory.isNullOrBlank() && match.editorialStory.length > 30) {
                val headline = if (!match.editorialHeadline.isNullOrBlank()) {
                    "### ${match.editorialHeadline}\n\n"
                } else {
                    "### Match Preview: $home vs $away\n\n"
                }
                val source = if (!match.editorialSource.isNullOrBlank()) "\n\n*Source: ${match.editorialSource}.*" else ""
                return "$headline${match.editorialStory}$source"
            }
            return generateUpcomingPreview(match)
        }

        // 2. Finished or Live Matches: Prioritize accredited editorial journalism if available
        if (!match.editorialStory.isNullOrBlank() && match.editorialStory.length > 30) {
            val headline = if (!match.editorialHeadline.isNullOrBlank()) {
                "### ${match.editorialHeadline}\n\n"
            } else {
                "### Match Summary: $home vs $away\n\n"
            }
            val source = if (!match.editorialSource.isNullOrBlank()) "\n\n*Source: ${match.editorialSource}.*" else ""
            return "$headline${match.editorialStory}$source"
        }

        // 3. Stored recap analysis from Supabase
        if (!match.recapAnalysis.isNullOrBlank() && match.recapAnalysis.length > 50) {
            return match.recapAnalysis
        }

        // 4. Algorithmic tactical match breakdown
        return generateMatchSummary(match)
    }

    private fun generateUpcomingPreview(match: Match): String {
        val home = match.homeTeamName.ifBlank { "Home Team" }
        val away = match.awayTeamName.ifBlank { "Away Team" }
        val comp = match.competitionName.ifBlank { "Official League" }

        return """
            |### Upcoming Tactical Preview: $home vs $away
            |$home host $away in what promises to be a high-stakes $comp encounter. Both managers are expected to deploy contrasting tactical setups, with $home likely controlling central progression through structured midfield rotations, while $away will look to exploit transition spaces through rapid counter-attacks.
            |
            |### Key Tactical Focus Areas:
            |- **Pressing Structure:** High-block pressing triggers against central distribution.
            |- **Midfield Control:** Transition duels and second-ball dominance in the final third.
            |- **Set-Piece Delivery:** Decisive delivery into the box against organized zonal marking.
            |
            |*Preview generated by Football Highlights & Clips Tactical Engine.*
        """.trimMargin()
    }

    private fun generateMatchSummary(match: Match): String {
        val home = match.homeTeamName.ifBlank { "Home Team" }
        val away = match.awayTeamName.ifBlank { "Away Team" }
        val comp = match.competitionName.ifBlank { "Official League" }
        val homeScore = match.homeScore ?: 0
        val awayScore = match.awayScore ?: 0

        val narrative: String
        val tacticalBreakdown: String
        val impact: String

        when {
            isLive(match) -> {
                narrative = "The match between $home and $away is currently live with the scoreline standing at **$home $homeScore - $awayScore $away**. Both sides are engaged in intense spatial battles across midfield channels, with high-intensity pressing shaping transition moments."
                tacticalBreakdown = "Tactical observation reveals $home actively seeking width to bypass central midfield traps, while $away maintains a compact defensive block looking to spring counter-pressing situations."
                impact = "With points on the line in $comp, current in-game score movements represent crucial swings in table positioning and qualification momentum."
            }
            homeScore > awayScore -> {
                val isCleanSheet = awayScore == 0
                val cleanSheetText = if (isCleanSheet) ", keeping a disciplined clean sheet" else ""
                narrative = "$home secured a commanding victory over $away with a final scoreline of **$homeScore - $awayScore** in $comp. $home dictated match tempo through dominant possession, aggressive counter-pressing, and sharp execution in the final third$cleanSheetText."
                tacticalBreakdown = "$home's positional play created consistent overloads in the half-spaces, destabilizing $away's defensive line. $away struggled to establish sustained possession under relentless pressure, leaving their defensive structure vulnerable during rapid transitional breaks."
                impact = "The 3 points represent a vital boost for $home in their $comp campaign, strengthening their table position, while $away will need tactical adjustments to address defensive transitions ahead of their next fixture."
            }
            awayScore > homeScore -> {
                val isCleanSheet = homeScore == 0
                val cleanSheetText = if (isCleanSheet) " while denying the hosts a single goal" else ""
                narrative = "$away claimed an impressive away victory, defeating $home **$awayScore - $homeScore** in an intense $comp clash. $away executed their game plan with clinical efficiency, absorbing sustained phases of pressure before striking decisive blows on the counter-attack$cleanSheetText."
                tacticalBreakdown = "$away's tactical discipline in a compact mid-block successfully neutralized $home's central playmakers. By forcing $home into wide areas and winning second balls in their defensive third, $away exploited open channels behind the advanced home fullbacks."
                impact = "A massive away result for $away, securing all 3 points on rival territory in $comp. For $home, the setback highlights areas for defensive reorganization and attacking precision in upcoming matchdays."
            }
            else -> {
                val isGoalless = homeScore == 0 && awayScore == 0
                narrative = if (isGoalless) {
                    "$home and $away shared the spoils in a hard-fought **0 - 0** stalemate in $comp. Both defensive units remained impenetrable, prioritizing organizational structure and shutting down dangerous scoring avenues throughout 90 minutes."
                } else {
                    "$home and $away delivered an electrifying contest ending in a **$homeScore - $awayScore** draw in $comp. An end-to-end spectacle featuring momentum swings, tactical parity, and clinical attacking responses from both managers."
                }
                tacticalBreakdown = "The tactical duel was defined by midfield equilibrium. Neither side surrendered positional discipline, with defensive lines holding high-line discipline and goalkeepers making key interventions during decisive counter-attacking sequences."
                impact = "A point apiece ensures both $home and $away stay within touching distance of their season targets in $comp, demonstrating tactical resilience against quality opposition."
            }
        }

        return """
            |### Match Overview & Decisive Moments
            |$narrative
            |
            |### Tactical Architecture & Spatial Duels
            |$tacticalBreakdown
            |
            |### Standings & Season Impact
            |$impact
            |
            |*Verified Match Analysis by Football Highlights & Clips Tactical Engine.*
        """.trimMargin()
    }
}
